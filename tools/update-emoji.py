#!/usr/bin/env python3
"""Build the oj Emoji catalogue from Unicode Emoji 16.0 (no third-party modules)."""
import argparse
import hashlib
from pathlib import Path
import re
from urllib.request import urlopen

VERSION = "16.0"
URL = f"https://www.unicode.org/Public/emoji/{VERSION}/emoji-test.txt"
ROOT = Path(__file__).resolve().parents[1]
FAVORITES = "😀 😃 😄 😁 😆 😅 😂 🤣 😊 😍 😘 😎 🤔 😭 😡 👍 👏 🙏 🎉 🚀".split()
# One common prefix, 26 category suffixes. Each supported Unicode subgroup is
# assigned exactly once; new upstream subgroups require an explicit decision.
CATEGORIES = [
    ("a", "笑脸开心", "face-smiling face-tongue face-hand face-hat face-glasses face-costume cat-face monkey-face"),
    ("b", "情绪表情", "face-neutral-skeptical face-sleepy face-unwell face-concerned face-negative"),
    ("c", "爱心亲密", "face-affection heart emotion"),
    ("d", "手势身体", "hand-fingers-open hand-fingers-partial hand-single-finger hand-fingers-closed hands hand-prop body-parts"),
    ("e", "人物身份", "person person-gesture person-role person-fantasy person-activity person-resting family person-symbol"),
    ("f", "动物昆虫", "animal-mammal animal-bird animal-amphibian animal-reptile animal-marine animal-bug"),
    ("g", "花草植物", "plant-flower plant-other"),
    ("h", "天气天象", "sky-weather"),
    ("i", "水果蔬菜", "food-fruit food-vegetable"),
    ("j", "餐食甜点", "food-prepared food-asian food-sweet"),
    ("k", "饮品餐具", "drink dishware"),
    ("l", "运动奖牌", "person-sport award-medal sport"),
    ("m", "游戏娱乐", "game"),
    ("n", "音乐艺术", "arts-crafts sound music musical-instrument light-video"),
    ("o", "交通车辆", "transport-ground transport-water transport-air"),
    ("p", "旅行建筑", "place-map place-geographic place-building place-religious place-other hotel"),
    ("q", "科技设备", "phone computer science lock"),
    ("r", "服饰配件", "clothing"),
    ("s", "日用工具", "tool medical household other-object"),
    ("t", "节庆礼物", "event"),
    ("u", "标志符号", "transport-sign warning gender math punctuation other-symbol"),
    ("v", "箭头按钮", "arrow av-symbol keycap alphanum"),
    ("w", "时间钟表", "time"),
    ("x", "钱财商务", "money currency"),
    ("y", "文书办公", "book-paper mail writing office"),
    ("z", "星座图形旗帜", "religion zodiac geometric flag"),
]
SUBGROUP = {sub: letter for letter, _, names in CATEGORIES for sub in names.split()}
ALIASES = {"sky & weather": "sky-weather", "arts & crafts": "arts-crafts", "light & video": "light-video"}
ROW = re.compile(r"^([0-9A-F ]+)\s*;\s*fully-qualified\s*#\s*.*?\s+E[0-9.]+\s+(.*)$")


def generate(data):
    text = data.decode("utf-8")
    if f"# Version: {VERSION}" not in text:
        raise ValueError(f"Expected Unicode Emoji {VERSION} input")
    groups = {letter: [] for letter, _, _ in CATEGORIES}
    all_emoji = []
    seen = set()
    subgroup = ""
    excluded = 0
    for line in text.splitlines():
        if line.startswith("# subgroup:"):
            subgroup = line.split(":", 1)[1].strip()
            subgroup = ALIASES.get(subgroup, subgroup)
        match = ROW.match(line)
        if not match:
            continue
        points = [int(cp, 16) for cp in match[1].split()]
        # The renderer supports one base glyph plus an optional emoji variation
        # selector. Do not claim to shape ZWJ, skin-tone or country-flag clusters.
        if not (len(points) == 1 or len(points) == 2 and points[1] == 0xFE0F):
            excluded += 1
            continue
        if any(0x1F3FB <= cp <= 0x1F3FF for cp in points):
            excluded += 1
            continue
        emoji = "".join(chr(cp) for cp in points)
        if emoji in seen:
            continue
        seen.add(emoji)
        if subgroup not in SUBGROUP:
            raise ValueError(f"Unmapped Unicode Emoji subgroup: {subgroup}")
        # Briefcase is more useful in the business category than stationery.
        category = "x" if emoji == "💼" else SUBGROUP[subgroup]
        groups[category].append(emoji)
        all_emoji.append(emoji)
    if any(not values for values in groups.values()):
        raise ValueError("All 26 categories must have candidates")
    if any(emoji not in seen for emoji in FAVORITES):
        raise ValueError("Existing favorite candidates must be preserved")
    overview = FAVORITES + [emoji for emoji in all_emoji if emoji not in FAVORITES]
    digest = hashlib.sha256(data).hexdigest()
    lines = [
        f"# Generated by tools/update-emoji.py from Unicode Emoji {VERSION}.",
        f"# Source: {URL}",
        f"# Source SHA-256: {digest}",
        "# Unicode data copyright Unicode, Inc.; see UNICODE-LICENSE.txt.",
        "# One entry oj; category suffixes oja..ojz. Existing base codes win.",
        f"# Unique candidates: {len(overview)}; excluded complex sequences: {excluded}.",
        "KeyCode=abcdefghijklmnopqrstuvwxyz", "Length=3", "Label[oj]=Emoji · 常用总览",
    ]
    lines += [f"Label[oj{letter}]=Emoji · {name}" for letter, name, _ in CATEGORIES]
    lines += ["[Data]"]
    lines += [f"oj {emoji}" for emoji in overview]
    for letter, _, _ in CATEGORIES:
        lines += [f"oj{letter} {emoji}" for emoji in groups[letter]]
    return "\n".join(lines) + "\n", groups, len(overview), excluded, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, help="Use a local emoji-test.txt instead of downloading")
    parser.add_argument("--output", type=Path, default=ROOT / "src/assets/emoji.txt")
    args = parser.parse_args()
    if args.source:
        data = args.source.read_bytes()
    else:
        with urlopen(URL, timeout=60) as response:
            data = response.read()
    catalogue, groups, total, excluded, digest = generate(data)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(catalogue, encoding="utf-8")
    print(f"Unique Emoji: {total}; omitted complex sequences: {excluded}; source SHA-256: {digest}")
    for letter, name, _ in CATEGORIES:
        print(f"oj{letter}\t{name}\t{len(groups[letter])}\t{''.join(groups[letter][:5])}")
    print(f"Written: {args.output}")


if __name__ == "__main__":
    main()
